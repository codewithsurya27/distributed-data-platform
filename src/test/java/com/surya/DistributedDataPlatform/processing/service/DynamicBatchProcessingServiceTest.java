
package com.surya.DistributedDataPlatform.processing.service;

import com.surya.DistributedDataPlatform.jobs.dto.DestinationTableMetadata;
import com.surya.DistributedDataPlatform.jobs.entity.IngestionJob;
import com.surya.DistributedDataPlatform.jobs.repository.IngestionJobRepository;
import com.surya.DistributedDataPlatform.jobs.service.PostgreSqlDestinationService;
import com.surya.DistributedDataPlatform.processing.dynamic.DynamicCsvRow;
import com.surya.DistributedDataPlatform.processing.dynamic.DynamicCsvValidationResult;
import com.surya.DistributedDataPlatform.processing.dynamic.DynamicCsvValidationService;
import com.surya.DistributedDataPlatform.processing.parser.CsvRecordParser;
import com.surya.DistributedDataPlatform.processing.validator.CustomerRecordValidator;
import io.micrometer.core.instrument.simple.SimpleMeterRegistry;
import org.junit.jupiter.api.Test;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.UUID;

import static org.mockito.Mockito.*;

class DynamicBatchProcessingServiceTest {

    @Test
    void routesDestinationJobThroughDynamicPipeline() throws Exception {

        Path csv = Files.createTempFile("dynamic-ingestion", ".csv");

        try {
            Files.writeString(csv, "customer_id,name\nC001,Alice\n");

            IngestionJob job = new IngestionJob(
                    "customers.csv",
                    csv.toString(),
                    "public",
                    "customer_records"
            );

            // Use the ID generated by the entity itself.
            UUID jobId = job.getId();

            IngestionJobRepository jobs = mock(IngestionJobRepository.class);
            BatchPersistenceService persistence = mock(BatchPersistenceService.class);

            DynamicCsvValidationService dynamicValidator =
                    mock(DynamicCsvValidationService.class);

            PostgreSqlDestinationService destinations =
                    mock(PostgreSqlDestinationService.class);

            DestinationTableMetadata metadata = new DestinationTableMetadata(
                    "public",
                    "customer_records",
                    List.of()
            );

            when(persistence.claimJob(jobId)).thenReturn(true);
            when(jobs.findById(jobId)).thenReturn(Optional.of(job));

            when(destinations.getTableMetadata("public", "customer_records"))
                    .thenReturn(metadata);

            when(dynamicValidator.validate(any(Path.class), eq(metadata)))
                    .thenReturn(new DynamicCsvValidationResult(
                            1,
                            List.of(new DynamicCsvRow(
                                    2,
                                    Map.of(
                                            "customer_id", "C001",
                                            "name", "Alice"
                                    )
                            )),
                            List.of()
                    ));

            BatchProcessingService service = new BatchProcessingService(
                    jobs,
                    new CsvRecordParser(),
                    new CustomerRecordValidator(),
                    persistence,
                    new SimpleMeterRegistry(),
                    10,
                    dynamicValidator,
                    destinations
            );

            service.process(jobId);

            verify(persistence).prepareDynamicAttempt(jobId);

            verify(persistence).saveDynamicBatch(
                    eq(jobId),
                    eq("public"),
                    eq("customer_records"),
                    eq(metadata),
                    anyList(),
                    anyList(),
                    eq(1L),
                    eq(1L),
                    eq(0L)
            );

            verify(persistence).finish(jobId, false);
            verify(persistence, never()).prepareAttempt(jobId);

        } finally {
            Files.deleteIfExists(csv);
        }
    }
}
